CREATE OR REPLACE VIEW public.tmc_metadata_:YEAR AS
  SELECT
      s.aadt::INTEGER,
      s.aadt_combi::INTEGER,
      s.aadt_singl::INTEGER,
      s.active_end_date,
      s.active_start_date,
      s.altrtename,
      s.border_set,
      s.conflation_year,
      m.country,
      s.direction,
      s.endlat,
      s.endlong,
      s.faciltype::SMALLINT,
      s.firstname,
      s.frc::SMALLINT,
      s.f_system::SMALLINT,
      s.intersection,
      s.isprimary,
      s.miles,
      s.nhs::SMALLINT,
      s.nhs_pct::SMALLINT,
      s.npmrds_shapefile_version,
      s.download_timestamp,
      s.ogc_fid,
      s.roadname,
      s.roadnumber,
      s.route_numb::INTEGER,
      s.route_qual::SMALLINT,
      s.route_sign::SMALLINT,
      s.startlat,
      s.startlong,
      m.state,
      s.strhnt_pct::SMALLINT,
      s.strhnt_typ::SMALLINT,
      s.structype::SMALLINT,
      s.thrulanes::SMALLINT,
      s.timezone_name,
      s.tmc,
      s.tmclinear::INTEGER,
      s.tmctype,
      s.truck::SMALLINT,
      s.zip,
      m.avg_speedlimit,
      m.avg_vehicle_occupancy,
      m.bounding_box,
      m.congestion_level,
      m.county_code,
      m.county_name,
      m.directionality,
      m.is_controlled_access,
      m.is_interstate,
      m.mpo_acrony,
      m.mpo_code,
      m.mpo_name,
      m.state_code,
      m.state_name,
      m.ua_code,
      m.ua_name
  FROM public.npmrds_shapefile_:YEAR AS s
    INNER JOIN public.tmc_metadata_:METADATA_YEAR AS m
    USING (tmc)
;
